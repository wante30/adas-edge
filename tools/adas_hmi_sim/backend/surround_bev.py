"""Lightweight four-camera BEV compositor for the RK3566 migration path.

The upstream surround-view projects use the same useful split: calibration is
done once, then every frame is rendered with cached image maps.  This module
keeps that runtime property while accepting ordinary BGR frames and a small
JSON configuration.  The checked-in default is an approximate planar layout
for PC demos; production cameras must provide measured homographies or the
fisheye calibration generated by the upstream project.
"""

from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Dict, Mapping, Optional, Sequence, Tuple

import cv2
import numpy as np


Role = str
Point = Tuple[float, float]

ROLES: Tuple[Role, ...] = ("front", "left", "right", "rear")
ROLE_ALIASES = {"back": "rear", "Cam_Front": "front", "Cam_Left": "left", "Cam_Right": "right", "Cam_Back": "rear"}

# Normalized destination quadrilaterals.  They deliberately overlap so the
# feathered masks hide most seams when no measured calibration is available.
DEFAULT_POLYGONS: Dict[Role, Tuple[Point, Point, Point, Point]] = {
    "front": ((0.14, 0.03), (0.86, 0.03), (0.98, 0.51), (0.02, 0.51)),
    "rear": ((0.02, 0.49), (0.98, 0.49), (0.86, 0.97), (0.14, 0.97)),
    "left": ((0.02, 0.03), (0.48, 0.27), (0.48, 0.73), (0.02, 0.97)),
    "right": ((0.52, 0.27), (0.98, 0.03), (0.98, 0.97), (0.52, 0.73)),
}


def _canonical_role(role: str) -> str:
    value = ROLE_ALIASES.get(str(role), str(role).lower())
    if value not in ROLES:
        raise ValueError(f"unsupported camera role: {role!r}")
    return value


def _points(value: Sequence[Sequence[float]], width: int, height: int) -> np.ndarray:
    if len(value) != 4:
        raise ValueError("a camera polygon must contain four points")
    return np.asarray([(float(x) * width, float(y) * height) for x, y in value], dtype=np.float32)


class SurroundBEVComposer:
    """Compose synchronized front/left/right/rear BGR frames into one BEV."""

    def __init__(self, config: Optional[Mapping] = None):
        spec = dict(config or {})
        output_size = spec.get("output_size", [640, 640])
        if len(output_size) != 2:
            raise ValueError("output_size must be [width, height]")
        self.width, self.height = int(output_size[0]), int(output_size[1])
        if self.width < 128 or self.height < 128:
            raise ValueError("BEV output is too small")
        self.calibration_mode = str(spec.get("calibration_mode", "APPROXIMATE_PLANAR"))
        input_size = spec.get("input_size", [640, 360])
        self.input_width, self.input_height = int(input_size[0]), int(input_size[1])
        if self.input_width < 64 or self.input_height < 64:
            raise ValueError("input_size is too small")
        polygons = dict(DEFAULT_POLYGONS)
        polygons.update(spec.get("camera_polygons", {}))
        self._maps: Dict[Role, Tuple[np.ndarray, np.ndarray]] = {}
        self._remap_cache: Dict[Tuple[str, Tuple[int, int]], Tuple[np.ndarray, np.ndarray]] = {}
        self._masks: Dict[Role, np.ndarray] = {}
        self._executor = ThreadPoolExecutor(max_workers=4)
        for role in ROLES:
            destination = _points(polygons[role], self.width, self.height)
            source = np.asarray([[0, 0], [1, 0], [1, 1], [0, 1]], dtype=np.float32)
            matrix = cv2.getPerspectiveTransform(source, destination)
            # Warp a unit square; the scale is corrected per input frame below.
            self._maps[role] = (matrix, destination)
            mask = np.zeros((self.height, self.width), dtype=np.uint8)
            cv2.fillConvexPoly(mask, destination.astype(np.int32), 255)
            feather = max(3, int(spec.get("feather_px", 15)))
            mask = cv2.GaussianBlur(mask, (feather * 2 + 1, feather * 2 + 1), 0)
            self._masks[role] = mask.astype(np.float32) / 255.0
        self._labels = {"front": "FRONT", "left": "LEFT", "right": "RIGHT", "rear": "REAR"}

    def close(self) -> None:
        """Release the worker pool owned by this compositor."""

        # ``cancel_futures`` is unavailable on the board's Python 3.8.
        self._executor.shutdown(wait=False)

    @classmethod
    def from_json(cls, path: Path) -> "SurroundBEVComposer":
        return cls(json.loads(Path(path).read_text(encoding="utf-8")))

    def metadata(self) -> Dict[str, object]:
        return {
            "calibration_mode": self.calibration_mode,
            "output_size": [self.width, self.height],
            "input_size": [self.input_width, self.input_height],
            "roles": list(ROLES),
            "renderer": "cached_planar_warp",
        }

    def compose(self, frames: Mapping[str, np.ndarray]) -> np.ndarray:
        canvas = np.zeros((self.height, self.width, 3), dtype=np.float32)
        weights = np.zeros((self.height, self.width), dtype=np.float32)
        present = []
        jobs = []
        for raw_role, image in frames.items():
            if image is None:
                continue
            role = _canonical_role(raw_role)
            if role in present:
                continue
            frame = np.asarray(image)
            if frame.ndim != 3 or frame.shape[2] != 3:
                raise ValueError(f"{role} frame must be a BGR HxWx3 image")
            jobs.append((role, frame))
            present.append(role)
        for role, warped in self._executor.map(self._warp_one, jobs):
            alpha = self._masks[role]
            canvas += warped.astype(np.float32) * alpha[..., None]
            weights += alpha
        valid = weights > 1e-4
        output = np.zeros_like(canvas, dtype=np.uint8)
        if np.any(valid):
            canvas[valid] /= weights[valid, None]
            output[valid] = np.clip(canvas[valid], 0, 255).astype(np.uint8)
        self._draw_overlay(output, present)
        return output

    def _warp_one(self, job: Tuple[str, np.ndarray]) -> Tuple[str, np.ndarray]:
        role, frame = job
        if frame.shape[1] != self.input_width or frame.shape[0] != self.input_height:
            frame = cv2.resize(frame, (self.input_width, self.input_height), interpolation=cv2.INTER_AREA)
        shape_key = (role, (frame.shape[1], frame.shape[0]))
        maps = self._remap_cache.get(shape_key)
        if maps is None:
            maps = self._build_remap(role, frame.shape[1], frame.shape[0])
            self._remap_cache[shape_key] = maps
        map_x, map_y = maps
        return role, cv2.remap(frame, map_x, map_y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0))

    def _build_remap(self, role: str, source_width: int, source_height: int) -> Tuple[np.ndarray, np.ndarray]:
        source = np.asarray([[0, 0], [source_width - 1, 0], [source_width - 1, source_height - 1], [0, source_height - 1]], dtype=np.float32)
        _, destination = self._maps[role]
        matrix = cv2.getPerspectiveTransform(destination, source)
        grid_x, grid_y = np.meshgrid(np.arange(self.width, dtype=np.float32), np.arange(self.height, dtype=np.float32))
        destination_grid = np.stack([grid_x, grid_y], axis=-1).reshape(-1, 1, 2)
        source_grid = cv2.perspectiveTransform(destination_grid, matrix).reshape(self.height, self.width, 2)
        map_x = source_grid[..., 0].astype(np.float32)
        map_y = source_grid[..., 1].astype(np.float32)
        return cv2.convertMaps(map_x, map_y, cv2.CV_16SC2)

    def _draw_overlay(self, image: np.ndarray, present: Sequence[str]) -> None:
        cx, cy = self.width // 2, self.height // 2
        car_w = max(22, int(self.width * 0.09))
        car_h = max(42, int(self.height * 0.16))
        cv2.rectangle(image, (cx - car_w, cy - car_h), (cx + car_w, cy + car_h), (20, 28, 31), -1)
        cv2.rectangle(image, (cx - car_w, cy - car_h), (cx + car_w, cy + car_h), (215, 238, 232), 2)
        cv2.arrowedLine(image, (cx, cy - car_h - 5), (cx, cy - car_h - 35), (61, 220, 227), 3, tipLength=0.35)
        for role in present:
            points = self._maps[role][1]
            px = int(np.mean(points[:, 0]))
            py = int(np.mean(points[:, 1]))
            cv2.putText(image, self._labels[role], (px - 28, py), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (220, 238, 233), 1, cv2.LINE_AA)
        cv2.putText(image, "BEV / APPROX CALIBRATION", (14, 24), cv2.FONT_HERSHEY_SIMPLEX, 0.48, (145, 211, 210), 1, cv2.LINE_AA)


def load_bev_config(path: Optional[Path]) -> Dict:
    if path is None:
        return {}
    return json.loads(Path(path).read_text(encoding="utf-8"))

